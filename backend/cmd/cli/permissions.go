package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/prawirdani/go-react-monorepo/config"
	"github.com/prawirdani/go-react-monorepo/internal/audit"
	"github.com/prawirdani/go-react-monorepo/internal/auth"
	"github.com/prawirdani/go-react-monorepo/internal/rbac"
	"github.com/prawirdani/go-react-monorepo/internal/user"
)

const permissionsCmdName = "permissions"

// clientPermissionPath is the generated catalog, relative to the repo root.
const clientPermissionPath = "client/packages/schemas/src/permission.ts"

var permissionsCmd = command{
	name:    permissionsCmdName,
	summary: "regenerate the client permission catalog",
	run:     runPermissions,
}

// runPermissions rewrites the client's permission catalog from the codes the
// domain services register. It is authoritative: rather than grepping for
// constants, it replays the same RegisterPermissions calls the services make at
// startup. In a checkout without the client (API only) it prints the catalog
// instead, so the codes can still be copied by hand.
func runPermissions(args []string) error {
	fs := flag.NewFlagSet(permissionsCmdName, flag.ContinueOnError)
	out := fs.String("out", "", "write to this file instead of the client catalog")
	if err := fs.Parse(args); err != nil {
		return err
	}

	perms := gatherPermissions()
	content := renderPermissions(perms)

	target := *out
	if target == "" {
		wd, err := os.Getwd()
		if err != nil {
			return fmt.Errorf("resolve working directory: %w", err)
		}
		target = findClientPermissionFile(wd)
	}

	// No client tree and no -out: print, so an API-only checkout can still
	// paste the codes wherever it keeps them.
	if target == "" {
		fmt.Print(content)
		return nil
	}

	if err := os.WriteFile(target, []byte(content), 0o600); err != nil {
		return fmt.Errorf("write %s: %w", target, err)
	}
	fmt.Fprintf(os.Stderr, "wrote %d permissions to %s\n", len(perms), target)

	return nil
}

// findClientPermissionFile walks up from startDir looking for the client
// catalog, so the command works from any directory inside the repo. It returns
// "" when the checkout has no client.
func findClientPermissionFile(startDir string) string {
	dir := startDir
	for {
		candidate := filepath.Join(dir, clientPermissionPath)
		if info, err := os.Stat(candidate); err == nil && !info.IsDir() {
			return candidate
		}

		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}
		dir = parent
	}
}

// renderPermissions formats the catalog the way the client file expects: biome
// formatting (tab indent, double quotes), a readonly tuple, and the derived
// Permission union.
func renderPermissions(perms []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by `make permissions` (cli permissions); DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Full catalog of permissions the backend defines (rbac.Permission). This is a\n")
	b.WriteString("// mirror of the server, not an enforcer: the server owns and enforces\n")
	b.WriteString("// authorization. Regenerate it whenever a domain registers a permission.\n")
	b.WriteString("export const PERMISSIONS = [\n")
	for _, p := range perms {
		fmt.Fprintf(&b, "\t%q,\n", p)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type Permission = (typeof PERMISSIONS)[number];\n")

	return b.String()
}

// gatherPermissions replays the service constructors to collect the
// registered permissions, returning a unique, sorted list.
func gatherPermissions() []string {
	authorizer := rbac.NewAuthorizer()

	// Constructors only store their dependencies and call RegisterPermissions,
	// so nil dependencies are safe here. Keep this in sync with the services
	// wired in cmd/api/container.go - a new domain that registers permissions
	// must be replayed here too.
	user.NewService(nil, nil, nil, authorizer, nil, nil, nil)
	audit.NewAuditService(authorizer, nil)
	auth.NewService(&config.Config{}, nil, nil, nil, authorizer, nil, nil, nil, nil, nil)

	seen := make(map[string]struct{})
	for _, perms := range authorizer.Permissions() {
		for perm := range perms {
			seen[string(perm)] = struct{}{}
		}
	}

	list := make([]string, 0, len(seen))
	for perm := range seen {
		list = append(list, perm)
	}
	sort.Strings(list)

	return list
}
