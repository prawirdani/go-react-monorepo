// permissionLiteral matches `<ident> rbac.Permission = "value"` declarations.
var permissionLiteral = regexp.MustCompile(`rbac\.Permission\s*=\s*"([^"]+)"`)

// TestGatherPermissions_CoversEveryDefinedPermission guards the hand-maintained
// registrar list in gatherPermissions: every rbac.Permission constant declared
// in internal/ must appear in the dumped set. Adding a domain (or a permission)
// without replaying its registrar then fails here instead of silently drifting.
func TestGatherPermissions_CoversEveryDefinedPermission(t *testing.T) {
	root := filepath.Join("..", "..", "internal")

	var defined []string
	seen := map[string]struct{}{}

	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || filepath.Ext(path) != ".go" || strings.HasSuffix(path, "_test.go") {
			return nil
		}

		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for _, m := range permissionLiteral.FindAllStringSubmatch(string(b), -1) {
			if _, ok := seen[m[1]]; ok {
				continue
			}
			seen[m[1]] = struct{}{}
			defined = append(defined, m[1])
		}
		return nil
	})
	require.NoError(t, err)
	require.NotEmpty(t, defined, "expected to find permission constants under internal/")

	gathered := gatherPermissions()
	for _, perm := range defined {
		assert.Contains(t, gathered, perm, "declared permission missing from the dumped set")
	}
}

// TestRenderPermissions pins the shape the client imports: biome formatting
// (tab indent, double quotes) plus the readonly tuple and derived union, so a
// regenerated file never reformats or breaks the type.
func TestRenderPermissions(t *testing.T) {
	out := renderPermissions([]string{"audit.read", "user.restore"})

	assert.Contains(t, out, "// Code generated by `make permissions` (cli permissions); DO NOT EDIT.")
	assert.Contains(t, out, "export const PERMISSIONS = [\n\t\"audit.read\",\n\t\"user.restore\",\n] as const;")
	assert.Contains(t, out, "export type Permission = (typeof PERMISSIONS)[number];")
}

// TestFindClientPermissionFile covers the walk-up lookup and the API-only
// fallback that makes the command print instead of writing.
func TestFindClientPermissionFile(t *testing.T) {
	root := t.TempDir()
	catalog := filepath.Join(root, clientPermissionPath)
	require.NoError(t, os.MkdirAll(filepath.Dir(catalog), 0o755))
	require.NoError(t, os.WriteFile(catalog, []byte("export const PERMISSIONS = [];\n"), 0o644))

	t.Run("finds from a nested directory", func(t *testing.T) {
		nested := filepath.Join(root, "client", "apps", "dashboard", "src")
		require.NoError(t, os.MkdirAll(nested, 0o755))
		assert.Equal(t, catalog, findClientPermissionFile(nested))
	})

	t.Run("empty when there is no client tree", func(t *testing.T) {
		assert.Empty(t, findClientPermissionFile(t.TempDir()))
	})
}
